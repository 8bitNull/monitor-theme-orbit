import { test, expect } from '@playwright/test'
test('group and view survive ordinary links, reload and browser back', async ({page}) => {
  await page.goto('/')
  await page.locator('[aria-label="分组：全部"]').click()
  await page.getByRole('button',{name:'edge',exact:true}).click()
  await page.getByRole('button',{name:'列表视图',exact:true}).click()
  await page.locator('a[href^="/stats/"]').first().click()
  await page.getByRole('link',{name:'首页',exact:true}).click()
  await expect(page.locator('[aria-label="分组：edge"]')).toBeVisible()
  await page.reload()
  await expect(page.locator('[aria-label="分组：edge"]')).toBeVisible()
  await page.locator('a[href^="/stats/"]').first().click()
  await page.goBack()
  await expect(page.locator('[aria-label="分组：edge"]')).toBeVisible()
})
test('detail tab and hours track URL through changes and reload',async({page})=>{
  await page.goto('/stats/1/?tab=quality&hours=168')
  await expect(page.getByRole('button',{name:'7d',exact:true})).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'1h',exact:true}).click()
  await expect(page).toHaveURL(/tab=quality&hours=1/)
  await page.getByRole('tab',{name:'归属地与节点信息'}).click()
  await expect(page).toHaveURL(/tab=ip&hours=1/)
  await page.reload()
  await expect(page.getByText('公开视图',{exact:false})).toBeVisible()
})
test('corrupt storage and deleted selections recover',async({page})=>{
  await page.addInitScript(()=>{if (!sessionStorage.getItem('dstatus-dashboard-v1')) sessionStorage.setItem('dstatus-dashboard-v1','{')})
  await page.goto('/'); await expect(page.locator('a[href^="/stats/"]').first()).toBeVisible()
  await page.evaluate(()=>sessionStorage.setItem('dstatus-dashboard-v1',JSON.stringify({v:1,group:'deleted',region:'ZZ'})))
  await page.reload(); await expect(page.locator('[aria-label="分组：全部"]')).toBeVisible()
  await expect.poll(()=>page.evaluate(()=>JSON.parse(sessionStorage.getItem('dstatus-dashboard-v1')!).region)).toBe(null)
})
test('restores dashboard scroll after detail and browser back',async({page})=>{
  await page.goto('/'); await expect(page.locator('a[href^="/stats/"]').first()).toBeVisible()
  await page.evaluate(()=>window.scrollTo(0,800)); await page.waitForTimeout(150)
  const y=await page.evaluate(()=>scrollY)
  await page.locator('a[href^="/stats/"]').last().evaluate((a:HTMLAnchorElement)=>a.click())
  await page.waitForURL(/\/stats\//); await page.goBack()
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBeGreaterThan(y-40)
  expect(await page.evaluate(()=>scrollY)).toBeLessThanOrEqual(y+40)
})

test('direct IP URL remains safe for visitors, private and invalid detail nodes',async({page})=>{
  await page.route('**/api/nodes',async route=>{
    const data=await (await route.fetch()).json()
    data.nodes=data.nodes.map((n:object,i:number)=>({...n,public:i!==0,ip:'203.0.113.55',hostname:'synthetic-secret-host',remark:'synthetic-secret-remark'}))
    await route.fulfill({json:data})
  })
  await page.goto('/stats/2/?tab=ip&hours=24')
  await expect(page.getByText('公开视图',{exact:false})).toBeVisible()
  await expect(page.getByText('203.0.113.55',{exact:true})).toHaveCount(0)
  await expect(page.getByText('synthetic-secret-host')).toHaveCount(0)
  await page.goto('/stats/1/?tab=ip'); await expect(page.getByText('节点不存在或未公开。')).toBeVisible()
  await page.goto('/stats/999999/?tab=ip'); await expect(page.getByText('节点不存在或未公开。')).toBeVisible()
  expect(await page.evaluate(()=>JSON.stringify({...sessionStorage,...localStorage}))).not.toContain('synthetic-secret')
})
test('direct IP URL masks data during administrator downgrade',async({page})=>{
  let admin=true
  await page.route('**/api/me',route=>route.fulfill({json:{authed:admin,public_page:true}}))
  await page.route('**/api/nodes',async route=>{
    const data=await (await route.fetch()).json()
    data.nodes=data.nodes.map((n:object,i:number)=>({...n,public:i!==0,addresses:[{address:'203.0.113.56',source:'manual'}]}))
    await route.fulfill({json:data})
  })
  await page.goto('/stats/1/?tab=ip&hours=168')
  await expect(page.getByText('203.0.113.56',{exact:true})).toBeVisible()
  admin=false; await page.evaluate(()=>dispatchEvent(new Event('focus')))
  await expect(page.getByText('203.0.113.56',{exact:true})).toHaveCount(0)
  await expect(page.getByText('节点不存在或未公开。')).toBeVisible()
})
test('administrator-only group remains in memory and never enters storage',async({page})=>{
  await page.route('**/api/me',route=>route.fulfill({json:{authed:true,public_page:true}}))
  await page.route('**/api/nodes',async route=>{
    const data=await (await route.fetch()).json()
    data.nodes=data.nodes.map((n:object,i:number)=>({...n,public:i!==0,...(i===0?{group:'synthetic-private-group'}:{})}))
    await route.fulfill({json:data})
  })
  await page.goto('/')
  await page.locator('[aria-label="分组：全部"]').click()
  await page.getByRole('button',{name:'synthetic-private-group',exact:true}).click()
  await expect(page.locator('[aria-label="分组：synthetic-private-group"]')).toBeVisible()
  expect(await page.evaluate(()=>JSON.stringify({...sessionStorage,...localStorage}))).not.toContain('synthetic-private-group')
  await page.reload(); await expect(page.locator('[aria-label="分组：全部"]')).toBeVisible()
})
