import { test, expect } from '@playwright/test'

// Observe inline initialization before React can correct its attributes.
for (const accent of ['vercel-black','graphite-gray','classic-blue-black','warm-black','cool-black','invalid']) {
  test(`first frame validates ${accent} and resolves system dark`,async({page})=>{
    await page.emulateMedia({colorScheme:'dark'})
    await page.addInitScript(value=>{localStorage.setItem('theme','system');localStorage.setItem('dstatus-accent',value)},accent)
    await page.route('**/*',async route=>{
      if(route.request().isNavigationRequest()) {
        const response=await route.fetch()
        await route.fulfill({response,body:(await response.text()).replace(/<script type="module"[^>]*><\/script>/g,'')})
      } else await route.continue()
    })
    await page.goto('/')
    await expect(page.locator('script[type=module]')).toHaveCount(0)
    await expect(page.locator('#root')).toBeEmpty()
    await expect(page.getByTestId('boot-skeleton')).toBeVisible()
    expect(await page.getByTestId('boot-skeleton').evaluate(el=>getComputedStyle(el).color)).toBe('rgb(212, 212, 212)')
    await expect(page.getByTestId('node-card')).toHaveCount(0)
    await expect(page.locator('html')).toHaveClass(/dark/)
    await expect(page.locator('html')).toHaveAttribute('data-preset',accent==='invalid'?'vercel-black':accent)
    expect(await page.locator('html').getAttribute('style') ?? '').not.toContain('--accent-color:')
  })
}
test('presets, glass, explicit modes and system changes survive reload',async({page})=>{
  await page.emulateMedia({colorScheme:'dark'})
  await page.goto('/')
  for(const [label,id,color] of [['Vercel 纯黑','vercel-black','#0a0a0a'],['石墨深灰','graphite-gray','#171717'],['经典蓝黑','classic-blue-black','#0f172a'],['暖黑','warm-black','#1a1210'],['冷黑','cool-black','#0b1820']]) {
    await page.getByRole('button',{name:'主题',exact:true}).click()
    await page.getByRole('button',{name:label,exact:true}).click()
    await expect(page.locator('html')).toHaveAttribute('data-preset',id)
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('data-preset',id)
    expect(await page.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--card-bg-color').trim())).toBe(color)
  }
  await page.getByRole('button',{name:'主题',exact:true}).click()
  await page.getByRole('switch',{name:'玻璃效果'}).click()
  await page.getByRole('button',{name:'夜间模式',exact:true}).click()
  await page.reload(); await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.locator('html')).toHaveAttribute('data-glass','on')
  await page.getByRole('button',{name:'主题',exact:true}).click()
  await page.getByRole('button',{name:'日间模式',exact:true}).click()
  await page.reload(); await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.getByRole('button',{name:'主题',exact:true}).click()
  await page.getByRole('button',{name:'系统适配',exact:true}).click()
  await page.emulateMedia({colorScheme:'dark'}); await expect(page.locator('html')).toHaveClass(/dark/)
  await page.emulateMedia({colorScheme:'light'}); await expect(page.locator('html')).not.toHaveClass(/dark/)
})
test('reset only appearance preserves browsing state',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'分组：全部',exact:true}).click()
  await page.getByRole('button',{name:'edge',exact:true}).click()
  await page.getByRole('button',{name:'列表视图',exact:true}).click()
  const before=await page.evaluate(()=>sessionStorage.getItem('dstatus-dashboard-v1'))
  await page.getByRole('button',{name:'主题',exact:true}).click()
  await page.getByRole('button',{name:'冷黑',exact:true}).click()
  await page.getByRole('switch',{name:'玻璃效果'}).click()
  await page.getByRole('button',{name:'恢复默认外观',exact:true}).click()
  await expect(page.getByRole('button',{name:'分组：edge',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>sessionStorage.getItem('dstatus-dashboard-v1'))).toBe(before)
  expect(await page.evaluate(()=>['theme','dstatus-accent','dstatus-glass'].map(k=>localStorage.getItem(k)))).toEqual([null,null,null])
  await expect(page.locator('html')).toHaveAttribute('data-preset','vercel-black')
  await expect(page.locator('html')).not.toHaveAttribute('data-glass','on')
})
test('blocked storage still initializes system and allows current appearance changes',async({page})=>{
  await page.emulateMedia({colorScheme:'dark'})
  await page.addInitScript(()=>{for(const method of ['getItem','setItem','removeItem'])Object.defineProperty(Storage.prototype,method,{value(){throw new DOMException('blocked','SecurityError')}})})
  await page.goto('/')
  await expect(page.locator('html')).toHaveClass(/dark/)
  await page.getByRole('button',{name:'主题',exact:true}).click()
  await page.getByRole('button',{name:'日间模式',exact:true}).click()
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.getByRole('button',{name:'主题',exact:true}).click()
  await page.getByRole('button',{name:'暖黑',exact:true}).click()
  await expect(page.locator('html')).toHaveAttribute('data-preset','warm-black')
  await page.getByRole('switch',{name:'玻璃效果'}).click()
  await expect(page.locator('html')).toHaveAttribute('data-glass','on')
  await page.getByRole('button',{name:'恢复默认外观',exact:true}).click()
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.locator('html')).toHaveAttribute('data-preset','vercel-black')
})
