import {test,expect} from '@playwright/test'
test('search clearing and attention produce truthful results',async({page})=>{
 await page.goto('/')
 await expect(page.getByText('标签',{exact:true})).toHaveCount(0)
 await page.getByRole('textbox',{name:'搜索节点名称',exact:true}).fill('不存在的节点')
 await expect(page.getByText('没有符合筛选条件的节点。',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'清除全部筛选',exact:true}).click()
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:/离线节点$/}).click()
 await expect(page.getByText('Demo 离线节点 15',{exact:true})).toBeVisible()
 await expect(page.getByText('Demo 北京 01',{exact:true})).toHaveCount(0)
})
test('network target selection keeps history requests and detail context',async({page})=>{
 let requests=0
 page.on('request',r=>{if(/\/api\/nodes\/\d+\/metrics/.test(r.url())) requests++})
 await page.goto('/network-quality')
 await expect(page.getByPlaceholder('搜索节点名称',{exact:true})).toBeVisible()
 const select=page.getByRole('combobox',{name:'监控目标',exact:true})
 await expect(select.locator('option')).not.toHaveCount(1)
 await expect(page.getByText('正在加载历史…',{exact:false})).toHaveCount(0)
 expect(requests).toBeGreaterThan(0)
 const before=requests
 await select.selectOption({index:1})
 await expect(select).not.toHaveValue('all')
 expect(requests).toBe(before)
 await page.getByRole('button',{name:'6 小时',exact:true}).click()
 await expect(page.locator('a[href*="tab=quality&hours=6"]').first()).toBeVisible()
})
test('clear filters retains view and search stays out of storage',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'列表视图',exact:true}).click()
 await page.getByRole('textbox',{name:'搜索节点名称',exact:true}).fill('synthetic-private-query')
 await expect(page.getByRole('button',{name:'清除名称：synthetic-private-query',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>JSON.stringify({...sessionStorage,...localStorage}))).not.toContain('synthetic-private-query')
 await page.getByRole('button',{name:'清除全部筛选',exact:true}).click()
 await expect(page.getByRole('textbox',{name:'搜索节点名称',exact:true})).toHaveValue('')
 await expect(page.getByRole('button',{name:'列表视图',exact:true})).toHaveClass(/active/)
})
test('no public nodes is distinct from no search matches',async({page})=>{
 await page.route('**/api/nodes',route=>route.fulfill({json:{nodes:[]}}))
 await page.goto('/')
 await expect(page.getByText('尚无公开节点',{exact:true})).toBeVisible()
 await expect(page.getByText('没有符合筛选条件的节点。',{exact:true})).toHaveCount(0)
})
test('target options include unsampled probes and duplicate names while totals use filtered samples',async({page})=>{
 await page.route('**/api/nodes',async route=>{
  const data=await (await route.fetch()).json()
  data.nodes=data.nodes.slice(0,2)
  await route.fulfill({json:data})
 })
 await page.route('**/api/nodes/*/metrics?*',route=>route.fulfill({json:{metrics:[],probes:{1:'Same',2:'Same',3:'No samples'},ping:[{task_id:1,ts:100,latency:10},{task_id:2,ts:100,latency:30},{task_id:1,ts:200,latency:100}],loss:{1:0,2:0}}}))
 await page.goto('/network-quality')
 const select=page.getByRole('combobox',{name:'监控目标',exact:true})
 await expect(select.getByRole('option',{name:'Same（#1）',exact:true})).toHaveCount(1)
 await expect(select.getByRole('option',{name:'Same（#2）',exact:true})).toHaveCount(1)
 await expect(select.getByRole('option',{name:'No samples',exact:true})).toHaveCount(1)
 const chip=(label:string)=>page.locator('section').first().locator('.quality-totals > div').filter({has:page.getByText(label,{exact:true})})
 await expect(chip('监测组合数')).toContainText('4')
 await expect(chip('有效桶延迟均值')).toContainText('60ms')
 await page.getByRole('textbox',{name:'搜索节点名称',exact:true}).fill('Demo 北京 01')
 await expect(chip('监测组合数')).toContainText('2')
 await select.selectOption('3')
 await expect(chip('监测组合数')).toContainText('0')
 await expect(chip('有效桶延迟均值')).toContainText('--')
})
