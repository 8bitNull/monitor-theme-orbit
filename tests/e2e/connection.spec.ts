import { test, expect } from '@playwright/test'
test('malformed frames retain HTTP fallback without crashing', async ({page}) => {
 const errors:string[]=[]; page.on('pageerror',e=>errors.push(e.message))
 await page.routeWebSocket('**/api/ws', socket=>socket.send('{bad-json'))
 await page.goto('/')
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
 await expect(page.getByText('轮询更新中',{exact:true})).toBeVisible()
 expect(errors).toEqual([])
})
test('failed fallback retains nodes while marking received data stale', async ({page}) => {
 await page.clock.install()
 await page.routeWebSocket('**/api/ws',socket=>socket.close())
 await page.goto('/')
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
 await page.route('**/api/nodes',route=>route.fulfill({status:503,body:'Unavailable'}))
 await page.clock.fastForward(16001)
 await expect(page.getByText('数据已过期',{exact:true})).toBeVisible()
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
 await page.unroute('**/api/nodes')
 await page.getByRole('button',{name:'重新连接',exact:true}).click()
 await expect(page.getByText('轮询更新中',{exact:true})).toBeVisible()
})
test('unauthorized fallback clears nodes and remains stopped', async ({page}) => {
 await page.clock.install()
 await page.routeWebSocket('**/api/ws',socket=>socket.close())
 await page.goto('/')
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
 let requests=0
 await page.route('**/api/me',route=>route.fulfill({status:401}))
 await page.route('**/api/nodes',route=>{requests++;return route.fulfill({status:401,body:'Unauthorized'})})
 await page.clock.fastForward(5001)
 await expect(page.getByText('Demo 北京 01',{exact:true})).toHaveCount(0)
 await page.clock.fastForward(15000)
 expect(requests).toBe(1)
})
test('authorization failure clears subscribed history and stops its old refresh lifecycle', async ({page}) => {
 await page.clock.install()
 await page.routeWebSocket('**/api/ws',socket=>socket.close())
 let histories=0
 await page.route('**/api/nodes/*/metrics?*',route=>{histories++;return route.fulfill({json:{metrics:[],ping:[{task_id:1,ts:120,latency:42}],probes:{'1':'Synthetic cached target'},loss:{}}})})
 await page.goto('/stats/1/')
 await page.getByRole('tab',{name:'网络质量',exact:true}).click()
 await expect(page.getByRole('button').filter({hasText:'Synthetic cached target'})).toBeVisible()
 await page.route('**/api/nodes',route=>route.fulfill({status:401,body:'Unauthorized'}))
 await page.clock.runFor(5001)
 await expect(page.getByRole('button').filter({hasText:'Synthetic cached target'})).toHaveCount(0)
 const before=histories
 await page.clock.runFor(61000)
 expect(histories).toBe(before)
})
test('hidden fallback pauses HTTP and repeated visible events share one refresh', async ({page}) => {
 await page.clock.install()
 await page.routeWebSocket('**/api/ws',socket=>socket.close())
 let requests=0
 await page.route('**/api/nodes',async route=>{requests++;await new Promise(r=>setTimeout(r,50));const response=await route.fetch();await route.fulfill({response})})
 await page.goto('/')
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'))})
 const before=requests
 await page.clock.runFor(16000)
 expect(requests).toBe(before)
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});for(let i=0;i<3;i++)document.dispatchEvent(new Event('visibilitychange'))})
 await expect.poll(()=>requests).toBe(before+1)
 await page.waitForTimeout(100)
 expect(requests).toBe(before+1)
})
test('valid websocket samples stop polling and malformed bursts have a five second fetch cooldown', async ({page}) => {
 await page.clock.install()
 let send!:(data:string)=>void
 await page.routeWebSocket('**/api/ws',socket=>{send=data=>socket.send(data)})
 let requests=0
 let snapshot:unknown
 await page.route('**/api/nodes',async route=>{requests++;const response=await route.fetch();snapshot=await response.json();await route.fulfill({json:snapshot})})
 await page.goto('/')
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
 send(JSON.stringify(snapshot))
 await expect(page.locator('.connection-status')).toHaveCount(0)
 const before=requests
 await page.clock.runFor(16000)
 expect(requests).toBe(before)
 for(let i=0;i<10;i++)send('{bad-json')
 await expect.poll(()=>requests).toBe(before+1)
 await page.waitForTimeout(100)
 expect(requests).toBe(before+1)
 await page.clock.runFor(5001)
 send(JSON.stringify({nodes:[{id:'bad',name:'invalid',online:true}]}))
 await expect.poll(()=>requests).toBe(before+2)
 await expect(page.getByText('Demo 北京 01',{exact:true})).toBeVisible()
})
