import {test,expect} from '@playwright/test'
import {installFixture} from './fixtures'
for(const width of [360,390,1440])for(const mode of ['light','dark'])test(`all detail sections directly visible ${width} ${mode}`,async({page})=>{
 await page.setViewportSize({width,height:1000})
 await page.addInitScript(mode=>localStorage.setItem('theme',mode),mode)
 const fixture=await installFixture(page,{admin:true})
 await page.goto('/stats/1/')
 const panel=page.getByRole('tabpanel')
 await expect(panel.getByRole('heading',{name:'处理器',exact:true})).toBeVisible()
 await expect.poll(()=>fixture.connected()).toBe(true)
 fixture.emitNodes(nodes=>nodes.map(n=>({...n,interval:5,hostname:'host-'+ 'very-long'.repeat(24)})))
 await expect(page.locator('.connection-status')).toHaveCount(0)
 await expect(panel.getByText(/Ubuntu 22.04/)).toBeVisible()
 await expect(panel.getByText(/25.00 CNY/)).toBeVisible()
 await expect(panel.getByText('TCP 连接',{exact:true})).toBeVisible()
 await expect(panel.getByRole('img',{name:/区间流量估算/})).toBeVisible()
 await expect(panel.getByRole('img',{name:/磁盘使用率历史/})).toBeVisible()
 await expect(panel.locator('details,summary,button[aria-expanded]')).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`artifacts/acceptance/detail-expanded/${width}-${mode}-overview.png`,fullPage:true})
 await page.getByRole('tab',{name:'网络质量',exact:true}).click()
 await expect(panel.getByText(/目标平均成功率：/)).toBeVisible()
 const target=panel.getByRole('button').filter({hasText:'Demo·国内入口'}).first()
 await expect(target).toBeVisible()
 await expect(panel.locator('details,summary,button[aria-expanded]')).toHaveCount(0)
 if(width<768)expect((await panel.getByRole('img',{name:/网络延迟趋势/}).boundingBox())!.y).toBeLessThan((await target.boundingBox())!.y)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`artifacts/acceptance/detail-expanded/${width}-${mode}-quality.png`,fullPage:true})
 await page.getByRole('tab',{name:'IP 与节点信息',exact:true}).click()
 await expect(panel.getByText('1.8.2',{exact:true})).toBeVisible()
 await expect(panel.getByText('每 5 秒',{exact:true})).toBeVisible()
 await expect(panel.getByText('6.1.0-18-amd64',{exact:true})).toBeVisible()
 await expect(panel.getByText('203.0.113.11',{exact:true})).toBeVisible()
 await expect(panel.locator('details,summary,button[aria-expanded]')).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`artifacts/acceptance/detail-expanded/${width}-${mode}-ip.png`,fullPage:true})
})
