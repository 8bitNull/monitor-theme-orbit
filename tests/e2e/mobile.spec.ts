import {test,expect} from '@playwright/test'
for(const width of [360,390,430]) test(`mobile ${width} shows nodes early without page overflow`,async({page})=>{
 await page.setViewportSize({width,height:844})
 const requests:string[]=[]
 page.on('request',r=>requests.push(r.url()))
 await page.goto('/')
 const card=page.locator('article.server-card').first()
 await expect(card).toBeVisible()
 await expect(page.getByText(/历史已完成/)).toHaveCount(0)
 expect((await card.boundingBox())!.y).toBeLessThanOrEqual(width===360?480:430)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
 await expect(card).toHaveAttribute('data-testid','node-card')
 const trigger=page.getByRole('button',{name:'地区与地图',exact:true})
 await expect(trigger).toHaveAttribute('aria-expanded','false')
 await trigger.click()
 await expect(trigger).toHaveAttribute('aria-expanded','true')
 await expect(page.getByRole('button',{name:'中国，4个节点',exact:true})).toBeVisible()
 expect(requests.some(url=>url.includes('earth-blue-marble'))).toBe(false)
})
